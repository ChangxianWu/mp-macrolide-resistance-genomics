#!/usr/bin/env python3
"""Genome-jackknife stability of the 25-SNP single-linkage group.

The group is defined by single-linkage clustering of core-genome SNP distances
at 25 SNPs. This script asks how stable that group is when genomes are removed
at random: 200 replicates at 10% and 20% removal. For each replicate it reports

  * how many surviving original group members fall in one component
    (retention), and how often retention is at least 90%;
  * how often all surviving members remain in a single connected component
    (single-component rate).

Inputs (generated by the pipeline):
  results/coresnp/MY9_SNP距离.phylip   pairwise distance matrix
                                       (substitutions per site; x 742,308 = SNPs)
  results/coresnp/MY9_紧克隆成员.tsv   original 25-SNP group membership

Outputs:
  results/coresnp/group_jackknife.json
  results/coresnp/group_jackknife.md
"""
import csv
import json
import os
import sys

import numpy as np
from scipy.sparse import csr_matrix
from scipy.sparse.csgraph import connected_components

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CS = os.path.join(BASE, "results", "coresnp")
CORE_SITES = 742308   # core positions (>=95% coverage) for the 646-assembly panel
THRESHOLD = 25        # SNPs
REPLICATES = 200
SEED = 20261027


def read_phylip(path):
    lines = open(path, encoding="utf-8").read().strip().splitlines()
    n = int(lines[0].strip())
    accs, rows = [], []
    for line in lines[1:]:
        parts = line.split()
        accs.append(parts[0])
        rows.append([float(x) for x in parts[1:]])
    d = np.array(rows, dtype=float)
    d = (d + d.T) / 2.0 * CORE_SITES
    np.fill_diagonal(d, 0.0)
    return accs, d


def components(d, idx):
    sub = d[idx][:, idx]
    adjacency = (sub <= THRESHOLD) & (sub > 0)
    return connected_components(csr_matrix(adjacency), directed=False)[1]


def main():
    accs, d = read_phylip(os.path.join(CS, "MY9_SNP距离.phylip"))
    n = len(accs)

    labels = components(d, np.arange(n))
    sizes = np.bincount(labels)
    group = np.where(labels == int(np.argmax(sizes)))[0]

    members_path = os.path.join(CS, "MY9_紧克隆成员.tsv")
    if os.path.exists(members_path):
        members = [r["ena_acc"] for r in
                   csv.DictReader(open(members_path, encoding="utf-8-sig"),
                                  delimiter="\t")]
        group_accs = {accs[i] for i in group}
        overlap = len(set(members) & group_accs)
        print(f"member-table overlap: {overlap}/{len(group)}", flush=True)
    else:
        overlap = None
    group_set = set(int(i) for i in group)

    rng = np.random.default_rng(SEED)
    out = {
        "tips": n,
        "core_sites": CORE_SITES,
        "threshold_snp": THRESHOLD,
        "original_group": int(len(group)),
        "member_table_overlap": overlap,
        "replicates": REPLICATES,
        "seed": SEED,
    }

    print(f"tips={n} group={len(group)}", flush=True)
    for frac in (0.10, 0.20):
        retention, single, largest = [], [], []
        for _ in range(REPLICATES):
            keep = np.ones(n, dtype=bool)
            keep[rng.choice(n, size=int(round(frac * n)), replace=False)] = False
            idx = np.where(keep)[0]
            lab = components(d, idx)
            counts = {}
            for i, gi in enumerate(idx):
                if int(gi) in group_set:
                    l = int(lab[i])
                    counts[l] = counts.get(l, 0) + 1
            surviving = sum(counts.values())
            best = max(counts.values()) if counts else 0
            retention.append(best / surviving if surviving else 0.0)
            single.append(best == surviving)
            largest.append(int(np.bincount(lab).max()))

        retention = np.array(retention)
        key = f"drop_{int(frac * 100)}pct"
        out[key] = {
            "retention_median": round(float(np.median(retention)), 4),
            "retention_q1": round(float(np.percentile(retention, 25)), 4),
            "retention_q3": round(float(np.percentile(retention, 75)), 4),
            "pct_single_component": round(100 * float(np.mean(single)), 1),
            "pct_retention_ge90": round(100 * float(np.mean(retention >= 0.9)), 1),
            "largest_component_median": int(np.median(largest)),
            "surviving_group_median": int(round((1 - frac) * len(group))),
        }
        print(key, out[key], flush=True)

    json_p = os.path.join(CS, "group_jackknife.json")
    with open(json_p, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)

    md = [
        "# Genome-jackknife stability of the 25-SNP single-linkage group",
        "",
        f"- Distance: core-genome SNP distance (substitutions/site x {CORE_SITES}).",
        f"- Threshold: {THRESHOLD} SNPs; original group n = {len(group)} of {n} genomes.",
        f"- Replicates: {REPLICATES} per removal level; seed {SEED}.",
        "",
        "| Removal | Retention median (IQR) | Single component | Retention >= 90% |",
        "|---|---|---|---|",
    ]
    for frac in (0.10, 0.20):
        r = out[f"drop_{int(frac * 100)}pct"]
        md.append(
            f"| {int(frac * 100)}% | {100 * r['retention_median']:.1f}% "
            f"({100 * r['retention_q1']:.1f}-{100 * r['retention_q3']:.1f}) "
            f"| {r['pct_single_component']:.1f}% | {r['pct_retention_ge90']:.1f}% |"
        )
    with open(os.path.join(CS, "group_jackknife.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(md) + "\n")
    print("written", json_p, flush=True)


if __name__ == "__main__":
    sys.exit(main())
